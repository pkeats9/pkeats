#!/usr/bin/env node
// Builds the icon layer from the real SVG files in assets/ (fetched with the /svg tool; never hand-drawn).
//   node tools/icons.mjs
// Writes public/js/icons.js (inline, animatable icons for JS-rendered UI) and refreshes the <symbol> sprite
// between the <!-- icons:start --> / <!-- icons:end --> markers in public/index.html (static markup).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\/>/g, "/>").replace(/>\s+</g, "><").trim();

// Lucide 1.75 stroke (ISC). Short names keep call sites readable.
const RENAME = { "map-pin": "pin", "map-pin-off": "pin-off", "chevron-left": "back", "chevron-right": "chevron",
  "shopping-bag": "bag", "trash-2": "trash", "user-round": "user", "triangle-alert": "alert", "arrow-up-right": "external" };
const paths = {};
for (const f of fs.readdirSync(path.join(root, "assets/icons")).filter((f) => f.endsWith(".svg")).sort()) {
  const base = f.replace(/^lucide-/, "").replace(/\.svg$/, "");
  paths[RENAME[base] || base] = inner(read(`assets/icons/${f}`));
}

// Brand marks (theSVG, CC0): mono ones follow currentColor; Google keeps its colours (ids namespaced).
const logos = {};
for (const f of fs.readdirSync(path.join(root, "assets/logos")).filter((f) => f.endsWith(".svg")).sort()) {
  const name = f.replace(/-mono\.svg$|\.svg$/g, "");
  let svg = read(`assets/logos/${f}`).replace(/<title>[\s\S]*?<\/title>/g, "").replace(/\s(role|xml:space|overflow)="[^"]*"/g, "");
  svg = svg.replace(/\bid="([^"]+)"/g, `id="${name}-$1"`).replace(/url\(#([^)]+)\)/g, `url(#${name}-$1)`).replace(/href="#([^"]+)"/g, `href="#${name}-$1"`);
  const vb = (svg.match(/viewBox="([^"]+)"/) || [])[1] || "0 0 24 24";
  const fill = /fill="currentColor"/.test(svg) ? ' fill="currentColor"' : "";
  logos[name] = { vb, fill, body: inner(svg) };
}

const js = `// Generated by tools/icons.mjs from assets/ — do not edit by hand.
// Icons: Lucide (lucide.dev, ISC) · Logos: theSVG (thesvg.org, CC0), fetched with the /svg tool.
export const PATHS = ${JSON.stringify(paths, null, 0).replace(/","/g, '",\n  "')};

export const LOGOS = ${JSON.stringify(logos, null, 0).replace(/},"/g, '},\n  "')};

const ATTR = 'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"';

/** Inline (animatable) icon markup. */
export function icon(name, cls = "") {
  return \`<svg class="i\${cls ? " " + cls : ""}" \${ATTR}>\${PATHS[name] || ""}</svg>\`;
}

/** Brand mark markup (mono marks inherit currentColor). */
export function logo(name, cls = "") {
  const l = LOGOS[name];
  return l ? \`<svg class="logo\${cls ? " " + cls : ""}" viewBox="\${l.vb}"\${l.fill} aria-hidden="true" focusable="false">\${l.body}</svg>\` : "";
}
`;
fs.writeFileSync(path.join(root, "public/js/icons.js"), js);

const STATIC = ["pin", "search", "back", "chevron", "x", "plus", "minus", "bag", "clock", "star", "ticket", "cookie", "user", "external", "info", "mail", "utensils", "search-x", "copy", "check"];
const sprite = `<svg class="sprite" aria-hidden="true" focusable="false"><!-- Lucide (lucide.dev, ISC), fetched with /svg; regenerate with tools/icons.mjs -->` +
  STATIC.map((n) => `<symbol id="i-${n}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${paths[n]}</g></symbol>`).join("") +
  `</svg>`;
const htmlPath = path.join(root, "public/index.html");
if (fs.existsSync(htmlPath)) {
  const html = fs.readFileSync(htmlPath, "utf8");
  const next = html.replace(/<!-- icons:start -->[\s\S]*?<!-- icons:end -->/, `<!-- icons:start -->${sprite}<!-- icons:end -->`);
  fs.writeFileSync(htmlPath, next);
}
console.log(`icons.js: ${Object.keys(paths).length} icons, ${Object.keys(logos).length} logos · sprite: ${STATIC.length} symbols`);
